#!/bin/sh
# Builds both distributions from bijan-design-principles.html and working-terms.md:
#   install.sh                         ~/.claude installer (local machine or cloud setup script)
#   dist/bijan-design-principles.zip   skill to upload at claude.ai
set -e
cd "$(dirname "$0")"

for f in working-terms.md bijan-design-principles.html; do
  if grep -q '^__BIJAN_EOF__$' "$f"; then
    echo "$f contains the heredoc delimiter; pick another" >&2
    exit 1
  fi
done

# --- install.sh ---
{
  cat <<'HEAD'
#!/bin/sh
# Installs Bijan's design principles into ~/.claude so every Claude Code session loads them.
# Generated by build.sh; edit the source files and rebuild instead of editing this.
# Safe to re-run: replaces its own block in ~/.claude/CLAUDE.md and leaves the rest alone.
set -e
dir="$HOME/.claude"
mkdir -p "$dir"

cat > "$dir/bijan-design-principles.html" <<'__BIJAN_EOF__'
HEAD
  cat bijan-design-principles.html
  echo '__BIJAN_EOF__'
  echo
  # A plain heredoc, not one inside $(...): bash 3.2 (macOS sh) misparses quotes there.
  echo "cat > \"\$dir/.bijan-block.tmp\" <<'__BIJAN_EOF__'"
  echo '<!-- bijan-design-principles:start -->'
  cat <<'INTRO'
# Bijan's design principles

Before any design, UX, UI, product-logic or creative-experience decision, read `~/.claude/bijan-design-principles.html` in full (the text; the CSS is presentation). It is the complete guide and its reasoning governs the work.

INTRO
  cat working-terms.md
  echo '<!-- bijan-design-principles:end -->'
  echo '__BIJAN_EOF__'
  cat <<'TAIL'

file="$dir/CLAUDE.md"
touch "$file"
awk '/^<!-- bijan-design-principles:start -->$/{skip=1} !skip{if($0==""){b++}else{while(b>0){print "";b--}print}} /^<!-- bijan-design-principles:end -->$/{skip=0}' "$file" > "$file.tmp"
mv "$file.tmp" "$file"
[ -s "$file" ] && printf '\n' >> "$file"
cat "$dir/.bijan-block.tmp" >> "$file"
rm "$dir/.bijan-block.tmp"
echo "Installed Bijan's design principles into $dir"
TAIL
} > install.sh
chmod +x install.sh
echo "Wrote install.sh"

# --- skill ---
stage=dist/stage/bijan-design-principles
rm -rf dist
mkdir -p "$stage"
cp bijan-design-principles.html "$stage/"
{
  cat <<'SKILL'
---
name: bijan-design-principles
description: Bijan's design principles (手応え), the governing guide for design work. Use before designing, building or reviewing any UI, UX, interaction, visual or audiovisual treatment, product logic, game, learning experience or other interactive or creative experience, and whenever Bijan's design preferences or 手応え come up.
---

# Bijan's design principles

1. Before the first design decision, read `bijan-design-principles.html` in this skill's folder in full (the text; the CSS is presentation). It is the complete guide; its reasoning governs the work alongside the project's own brief.
2. Work by the terms below throughout.

SKILL
  cat working-terms.md
} > "$stage/SKILL.md"
(cd dist/stage && zip -qr ../bijan-design-principles.zip bijan-design-principles)
rm -rf dist/stage
echo "Wrote dist/bijan-design-principles.zip"
